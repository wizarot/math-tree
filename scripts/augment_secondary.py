# 现有节点索引（按名称模糊匹配）
def norm(s): return (s or "").lower()
pool = []
for t in topics:
    pool.append(t)

def resolve(q):
    q = q.strip()
    if not q: return None
    # 1) 精确
    for t in pool:
        if norm(t.get("name_zh")) == norm(q) or norm(t.get("name")) == norm(q):
            return t["id"]
    # 2) 包含，取名称最短（最具体）的
    cands = []
    for t in pool:
        nm = t.get("name_zh") or ""
        en = t.get("name") or ""
        if q in nm or q in en:
            cands.append((len(nm), t["id"]))
    if cands:
        cands.sort()
        return cands[0][1]
    return None

